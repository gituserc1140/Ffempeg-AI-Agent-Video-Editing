GLYPHS = {ch: raw.split("/") for ch, raw in _RAW.items()}
CHARSET = set(GLYPHS)

for _ch, _rows in GLYPHS.items():
    assert len(_rows) == 7, _ch
    assert len({len(r) for r in _rows}) == 1, _ch


def glyph_width(ch):
    return len(GLYPHS[ch][0])


def text_width(text, scale=1):
    if not text:
        return 0
    return (sum(glyph_width(ch) + 1 for ch in text.upper()) - 1) * scale
