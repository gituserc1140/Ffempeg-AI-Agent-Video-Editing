def _parse(rows: str) -> list[tuple[int, int]]:
    lines = rows.split()
    if len(lines) != GLYPH_H or any(len(line) != GLYPH_W for line in lines):
        raise ValueError(f"bad glyph rows: {rows}")
    return [(x, y) for y, line in enumerate(lines) for x, ch in enumerate(line) if ch == "#"]


GLYPHS = {ch: _parse(rows) for ch, rows in _RAW.items()}


def text_width(text: str, scale: int = 1) -> int:
    if not text:
        return 0
    return (len(text) * ADVANCE - 1) * scale


def text_height(scale: int = 1) -> int:
    return GLYPH_H * scale


def text_points(text: str, x: int, y: int, scale: int = 1) -> list[tuple[int, int]]:
    """Canvas pixels lit by `text` with its top-left at (x, y)."""
    if scale < 1 or int(scale) != scale:
        raise ValueError("font scale must be a positive integer")
    points: list[tuple[int, int]] = []
    for i, ch in enumerate(text.upper()):
        glyph = GLYPHS.get(ch)
        if glyph is None:
            raise ValueError(f"no glyph for {ch!r} in {text!r}")
        gx = x + i * ADVANCE * scale
        for px, py in glyph:
            for sy in range(scale):
                for sx in range(scale):
                    points.append((gx + px * scale + sx, y + py * scale + sy))
    return points
